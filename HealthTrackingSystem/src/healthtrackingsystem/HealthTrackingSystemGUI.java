    private void displayAllRecords() {
        List<HealthRecord> allRecords = trackingList.getAllHealthRecord();
        if (allRecords.isEmpty()) {
            txtaDailyActivities.setText("No daily activity records entered yet.");
            txtaNutritionRecord.setText("No nutrition records entered yet.");
            txtaSleepRecord.setText("No sleep records entered yet.");
            return;
        }
        StringBuilder activitySb = new StringBuilder("Daily Activities:\n--------------------\n");
        StringBuilder nutritionSb = new StringBuilder("Nutrition Records:\n--------------------\n");
        StringBuilder sleepSb = new StringBuilder("Sleep Record:\n--------------------\n");

        for (HealthRecord record : allRecords) {
            if (record instanceof DailyActivity) {
                activitySb.append(record.displayRecord()).append("\n--------------------\n");
            } else if (record instanceof NutritionRecord) {
                nutritionSb.append(record.displayRecord()).append("\n--------------------\n");
            } else if (record instanceof SleepRecord) {
                sleepSb.append(record.displayRecord()).append("\n-------------------\n");
            }

        }
        txtaDailyActivities.setText(activitySb.toString());
        txtaNutritionRecord.setText(nutritionSb.toString());
        txtaSleepRecord.setText(sleepSb.toString());

    }

