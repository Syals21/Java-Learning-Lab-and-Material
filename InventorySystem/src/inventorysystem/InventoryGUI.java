    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        try {
            //avoid error when in editting mode on the table
            if (tblUpdateInventory.isEditing()) {
                tblUpdateInventory.getCellEditor().stopCellEditing();
            }
            
            //get selected row as newest update
            int selectedRow = tblUpdateInventory.getSelectedRow();
            if (selectedRow == -1) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Please click the row in the table to confirm your update before pressing the button.",
                        "Confirmation Required",
                        javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblUpdateInventory.getModel();

            // get all attributes in the table that already updated
            int id = Integer.parseInt(model.getValueAt(selectedRow, 0).toString());
            String name = model.getValueAt(selectedRow, 1).toString();
            String category = model.getValueAt(selectedRow, 2).toString();
            int quantity = Integer.parseInt(model.getValueAt(selectedRow, 3).toString());
            double price = Double.parseDouble(model.getValueAt(selectedRow, 4).toString());
            
            //create supplyItem Object for the updated value
            SupplyItem updatedItem = new SupplyItem(id, name, category, quantity, price);
            
            // connect db and add the item in array
            conn = DBConnection.getConnection();
            InventoryManager manager = new InventoryManager(conn);
            List<SupplyItem> items = new java.util.ArrayList<>();
            items.add(updatedItem);
            //call method updateStock to update in db
            manager.updateStock(items);
            
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Item updated successfully!",
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // Refresh everything as usual to keep newest data
            loadDashboardTable();
            refreshDashboardLabels();
            populateRemoveComboBox();
            populateUpdateComboBox();
            conn.close();
        } catch (NumberFormatException ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Please enter valid numeric values for Quantity and Price.",
                    "Input Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error updating item: " + ex.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnSearchByNameActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchByNameActionPerformed
        // TODO add your handling code here:
        try {
            //get text first
            String searchName = txtItemNameSearch.getText().trim();

            // Check if search field is empty
            if (searchName.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "Please enter an item name to search.",
                        "Input Required",
                        javax.swing.JOptionPane.WARNING_MESSAGE);
                return; 
            }
            
            //connect db and create object manager
            conn = DBConnection.getConnection();
            InventoryManager manager = new InventoryManager(conn);

            // get all item in db and pus as list items
            List<SupplyItem> items = manager.getAllSupplies();

            // Use lambda Predicate to filter by name
            List<SupplyItem> results = manager.filterItems(items,
                    item -> item.getName().toLowerCase().contains(searchName.toLowerCase()));

            // Display results in table
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblSearchResult.getModel();
            model.setRowCount(0); 
            for (SupplyItem item : results) {
                model.addRow(new Object[]{
                    item.getId(),
                    item.getName(),
                    item.getCategory(),
                    item.getQuantity(),
                    item.getPrice()
                });
            }
            
            if (results.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                        "No items found matching: " + searchName,
                        "Search Result",
                        javax.swing.JOptionPane.INFORMATION_MESSAGE);
            }

           conn.close();
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error searching items: " + ex.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        }


    }//GEN-LAST:event_btnSearchByNameActionPerformed

