    private void btnDisplayAllHealthRecordsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisplayAllHealthRecordsActionPerformed
        // TODO add your handling code here:
        int userId = Integer.parseInt(txtUserID4.getText());
        User user = trackingList.findUser(userId);

        if (user == null) {
            JOptionPane.showMessageDialog(this, "User not found!", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        StringBuilder report = new StringBuilder();

        report.append("=== HEALTH REPORT FOR: ").append(user.getName()).append(" ===\n");
        report.append("User ID : ").append(user.getUserId()).append("\n");
        report.append("Age     : ").append(user.getAge()).append("     | Gender : ").append(user.getGender()).append("\n");
        report.append("BMI     : ").append(String.format("%.2f", user.calculateBMI())).append(" (").append(user.resultBMI()).append(")\n\n");

        report.append("=== ACTIVITY RECORDS ===\n");
        for (HealthRecord r : trackingList.getAllHealthRecord()) {
            if (r instanceof DailyActivity && r.getUserID() == userId) {
                report.append("Record ID: ").append(r.getRecordID()).append("\n");
                report.append("Date: ").append(r.getDate()).append("\n");
                report.append(r.displayRecord()).append("\n\n");
            }
        }

        report.append("\n=== NUTRITION RECORDS ===\n");
        for (HealthRecord r : trackingList.getAllHealthRecord()) {
            if (r instanceof NutritionRecord && r.getUserID() == userId) {
                report.append("Record ID: ").append(r.getRecordID()).append("\n");
                report.append("Date: ").append(r.getDate()).append("\n");
                report.append(r.displayRecord()).append("\n\n");
            }
        }

        report.append("\n=== SLEEP RECORDS ===\n");
        for (HealthRecord r : trackingList.getAllHealthRecord()) {
            if (r instanceof SleepRecord && r.getUserID() == userId) {
                report.append("Record ID: ").append(r.getRecordID()).append("\n");
                report.append("Date: ").append(r.getDate()).append("\n");
                report.append(r.displayRecord()).append("\n");
            }
        }
        
        txtaReports.setText(report.toString());
    }//GEN-LAST:event_btnDisplayAllHealthRecordsActionPerformed

