    private void btnCalcCaloriesBurnedActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcCaloriesBurnedActionPerformed
        // TODO add your handling code here:
        int userId = Integer.parseInt(JOptionPane.showInputDialog(this, "Enter User ID to calculate total calories burned:"));

        User user = trackingList.findUser(userId);
        if (user != null) {
            double totalCalories = 0.0;

            for (HealthRecord record : trackingList.getAllHealthRecord()) {
                if (record instanceof DailyActivity && record.getUserID() == userId) {
                    DailyActivity activity = (DailyActivity) record;
                    totalCalories += activity.calculateCaloriesBurned();
                }
            }

            JOptionPane.showMessageDialog(this, "Total Calories Burned for User " + userId + ":\n" + String.format("%.2f", totalCalories) + " kcal");

        } else {
            JOptionPane.showMessageDialog(this, "User not found!", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnCalcCaloriesBurnedActionPerformed

