    // Method to refresh table in add item page
    private void refreshAddItemTable() throws InventoryException {
        
        try {
            //connect db
            conn = DBConnection.getConnection();
            InventoryManager manager = new InventoryManager(conn);

            // Get all items form db
            List<SupplyItem> allItems = manager.getAllSupplies();

            // Clear existing table data
            javax.swing.table.DefaultTableModel model
                    = (javax.swing.table.DefaultTableModel) tblInventory.getModel();
            model.setRowCount(0); 

            // Add new data to table
            for (SupplyItem item : allItems) {
                model.addRow(new Object[]{
                    item.getId(),
                    item.getName(),
                    item.getCategory(),
                    item.getQuantity(),
                    String.format("%.2f", item.getPrice())
                });
            }
            conn.close();
        } catch (SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error refreshing table: " + e.getMessage(),
                    "Database Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE);
        } finally {
            if (conn != null) {
                try {
                    conn.close();
                } catch (SQLException e) {
                    e.printStackTrace();
                }
            }
        }
    }

